// SYS-MCP-001: embeds every rule spec's §2 recipe into
// lib/src/mcp/recipes.dart (PLAN-03 R3: embedded specs).
//
// Usage (from the repository root):
//   dart tool/embed_recipes.dart          # regenerate the data file
//   dart tool/embed_recipes.dart --check  # exit 1 naming drifted rules
//
// The mcp sync test runs --check, so a spec §2 edit without
// re-embedding fails the suite. Line endings are normalized (CRLF ->
// LF) before comparison, so the check is stable on Windows.
import 'dart:io';

/// Heading that opens the embedded section (SYS-RECIPE-001).
const sectionHeading = '# 2. Canonical Auto-Heal Recipe';

void main(List<String> args) {
  final checkOnly = args.contains('--check');
  if (args.any((a) => a != '--check')) {
    stderr.writeln('Usage: dart tool/embed_recipes.dart [--check]');
    exit(2);
  }
  final root = File(Platform.script.toFilePath()).parent.parent.absolute.path;
  final specs =
      Directory('$root/specs')
          .listSync()
          .whereType<File>()
          .where(
            (f) => f.path.endsWith('.md') && !f.path.endsWith('_template.md'),
          )
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));
  if (specs.isEmpty) {
    stderr.writeln('error: no rule specs found under $root/specs');
    exit(1);
  }
  final entries = <({String id, String spec, String recipe})>[];
  for (final file in specs) {
    final text = File(file.path).readAsStringSync().replaceAll('\r\n', '\n');
    entries.add((
      id: _frontMatterId(text, file.path),
      spec: _repoRelative(root, file.path),
      recipe: _section(text, file.path),
    ));
  }
  entries.sort((a, b) => a.id.compareTo(b.id));
  final generated = _render(entries);
  final target = File('$root/lib/src/mcp/recipes.dart');
  if (checkOnly) {
    final committed = target.existsSync()
        ? target.readAsStringSync().replaceAll('\r\n', '\n')
        : '';
    if (committed != generated) {
      stderr.writeln('error: embedded recipes drifted from specs/TS-*.md.');
      stderr.writeln('run: dart tool/embed_recipes.dart');
      for (final missing in _drifted(committed, entries)) {
        stderr.writeln('drifted: $missing');
      }
      exit(1);
    }
    stdout.writeln('recipes in sync (${entries.length} rules).');
    return;
  }
  target.parent.createSync(recursive: true);
  target.writeAsStringSync(generated);
  stdout.writeln('wrote: ${target.path} (${entries.length} rules).');
}

/// Rule ids whose embedded recipe differs (or is absent) in [committed].
List<String> _drifted(
  String committed,
  List<({String id, String spec, String recipe})> entries,
) {
  return [
    for (final e in entries)
      if (!committed.contains("'${e.id}': r'''${e.recipe}'''")) e.id,
  ];
}

String _render(List<({String id, String spec, String recipe})> entries) {
  final recipes = entries
      .map((e) => "  '${e.id}': r'''${e.recipe}''',")
      .join('\n');
  final specs = entries.map((e) => "  '${e.id}': '${e.spec}',").join('\n');
  return '''// SYS-MCP-001: embedded §2 canonical recipes, keyed by rule id.
//
// GENERATED by `dart tool/embed_recipes.dart` from specs/TS-*.md — do
// not edit by hand. Re-run the generator after any spec §2 change;
// `dart tool/embed_recipes.dart --check` (run by the mcp sync test)
// fails naming drifted rules.
const canonicalRecipes = <String, String>{
$recipes
};

/// Owning spec contract per rule id (repo-relative paths).
const canonicalRecipeSpecs = <String, String>{
$specs
};
''';
}

/// `id` value from a spec's YAML front matter (minimal line parser,
/// mirroring the grader: no yaml dependency).
String _frontMatterId(String text, String path) {
  var inMatter = false;
  for (final line in text.split('\n')) {
    if (line.trim() == '---') {
      if (inMatter) break;
      inMatter = true;
      continue;
    }
    if (!inMatter) continue;
    final match = RegExp(r'^\s*id:\s*"?([^"\s]+)"?\s*$').firstMatch(line);
    if (match != null) return match.group(1)!;
  }
  stderr.writeln('error: no front-matter id in $path');
  exit(1);
}

/// Section text from [sectionHeading] through the line before the next
/// top-level (`# `) heading, with trailing blank lines trimmed.
String _section(String text, String path) {
  final lines = text.split('\n');
  final start = lines.indexWhere((l) => l.trim().startsWith(sectionHeading));
  if (start < 0) {
    stderr.writeln('error: no $sectionHeading in $path');
    exit(1);
  }
  var end = lines.length;
  for (var i = start + 1; i < lines.length; i++) {
    if (lines[i].startsWith('# ')) {
      end = i;
      break;
    }
  }
  final section = lines.sublist(start, end);
  while (section.isNotEmpty && section.last.trim().isEmpty) {
    section.removeLast();
  }
  final recipe = section.join('\n');
  if (recipe.contains("'''")) {
    stderr.writeln('error: triple-quote in §2, cannot embed: $path');
    exit(1);
  }
  return recipe;
}

String _repoRelative(String root, String path) {
  final normalized = path.replaceAll(r'\', '/');
  final prefix = root.replaceAll(r'\', '/');
  final relative = normalized.startsWith('$prefix/')
      ? normalized.substring(prefix.length + 1)
      : normalized;
  return relative;
}
